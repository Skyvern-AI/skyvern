"""HMAC-SHA256 signing and verification for bundled-artifact content URLs.

Signed URLs are generated by ArtifactManager._bundle_content_url() when
ARTIFACT_CONTENT_HMAC_KEYRING is set, and validated by the
GET /artifacts/{artifact_id}/content endpoint.

Canonical string (newline-separated):
    GET
    /v1/artifacts/{artifact_id}/content
    {expiry_unix_seconds}
    {kid}

The kid is part of the canonical string so that a signature produced with one
key cannot be replayed under a different key ID.

Key rotation
------------
Add the new key to the keyring's `keys` dict and set `current_kid` to it.
New URLs are signed with the new key immediately; old URLs carry the old kid
and verify against the old key (still present in `keys`) until they expire
(12 h max).  After that window remove the old key entry.
"""

import base64
import hashlib
import hmac
import json
import os
import re
import time
from functools import lru_cache
from typing import NamedTuple
from urllib.parse import parse_qsl, urlencode, urlsplit

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from pydantic import BaseModel, model_validator

from skyvern.constants import BROWSER_DOWNLOADING_SUFFIX, DOWNLOAD_FILE_PREFIX
from skyvern.forge.sdk.artifact.models import ArtifactType

ARTIFACT_URL_EXPIRY_SECONDS = 12 * 60 * 60  # 12 hours — global default when no per-org override.

# TTL for URLs minted at the point of use via GET /artifacts/{id}/signed-url.
# Short on purpose: the consumer asks for a fresh URL right before dereferencing
# it, so the window only needs to cover one fetch (or one video-buffering burst).
ARTIFACT_URL_ON_DEMAND_EXPIRY_SECONDS = 5 * 60

# Screenshots and recordings capture whatever the browser rendered — page content,
# filled form values, logged-in views — so their capability URLs get a tighter
# window than downloads, which API consumers routinely fetch on their own
# schedule. 1 hour is the floor `ARTIFACT_URL_EXPIRY_SECONDS_MIN` already
# guarantees webhook consumers; first-party viewers survive it by re-minting via
# GET /v1/artifacts/{id}/signed-url.
SENSITIVE_ARTIFACT_URL_EXPIRY_SECONDS = 60 * 60

SENSITIVE_ARTIFACT_TYPES: frozenset[ArtifactType] = frozenset(
    {
        ArtifactType.RECORDING,
        ArtifactType.SESSION_REPLAY,
        ArtifactType.SCREENSHOT,
        ArtifactType.SCREENSHOT_LLM,
        ArtifactType.SCREENSHOT_ACTION,
        ArtifactType.SCREENSHOT_FINAL,
        ArtifactType.SCREENSHOT_PROXY,
        ArtifactType.SCREENSHOT_PRE_SUBMIT,
        ArtifactType.HTML_PRE_SUBMIT,
        # A row this image cannot classify gets the short TTL, not the default one.
        ArtifactType.UNKNOWN,
    }
)

# Bounds for the per-org override. 1 hour minimum keeps URLs useful for webhook
# consumers that retry across short outages; 7 days maximum follows the AWS S3
# presigned-URL cap so customers used to S3 don't get surprised. The route
# validates inbound values against these and the helper below clamps to them
# defensively in case a stray DB write puts garbage in the column.
ARTIFACT_URL_EXPIRY_SECONDS_MIN = 60 * 60  # 1 hour
ARTIFACT_URL_EXPIRY_SECONDS_MAX = 7 * 24 * 60 * 60  # 7 days

_ARTIFACT_CONTENT_PATH_TEMPLATE = "/v1/artifacts/{artifact_id}/content"
_ARTIFACT_CONTENT_PATH_RE = re.compile(r"^/v1/artifacts/(?P<artifact_id>[^/]+)/content$")
S3_DOWNLOAD_FALLBACK_PREFIX = "s3-download-"
_S3_DOWNLOAD_FALLBACK_KEY_INFO = b"skyvern.artifact-content.s3-download-fallback.v1"
_S3_DOWNLOAD_FALLBACK_NONCE_BYTES = 12


class ParsedArtifactContentUrl(NamedTuple):
    artifact_id: str
    expiry: str | None
    kid: str | None
    sig: str | None


class S3DownloadFallback(NamedTuple):
    key: str
    organization_id: str
    filename: str


def _s3_download_fallback_cipher(secret: bytes) -> AESGCM:
    key = HKDF(
        algorithm=hashes.SHA256(),
        length=32,
        salt=None,
        info=_S3_DOWNLOAD_FALLBACK_KEY_INFO,
    ).derive(secret)
    return AESGCM(key)


def sign_s3_download_fallback_url(
    base_url: str,
    *,
    bucket: str,
    key: str,
    filename: str,
    keyring: "ArtifactHmacKeyring",
    expiry_seconds: int,
) -> str:
    kid = keyring.current_kid
    secret = keyring.get_secret_bytes(kid)
    if secret is None:
        raise ValueError("No current key for standalone download fallback")
    payload = json.dumps([bucket, key, filename], separators=(",", ":"), ensure_ascii=False).encode()
    nonce = os.urandom(_S3_DOWNLOAD_FALLBACK_NONCE_BYTES)
    ciphertext = _s3_download_fallback_cipher(secret).encrypt(nonce, payload, kid.encode())
    artifact_id = S3_DOWNLOAD_FALLBACK_PREFIX + base64.urlsafe_b64encode(nonce + ciphertext).rstrip(b"=").decode()
    return sign_artifact_url(
        base_url,
        artifact_id,
        keyring,
        expiry_seconds=min(expiry_seconds, ARTIFACT_URL_EXPIRY_SECONDS_MAX),
    )


def decode_s3_download_fallback(
    artifact_id: str, *, bucket: str, environment: str, kid: str, keyring: "ArtifactHmacKeyring"
) -> S3DownloadFallback | None:
    if not artifact_id.startswith(S3_DOWNLOAD_FALLBACK_PREFIX):
        return None
    secret = keyring.get_secret_bytes(kid)
    if secret is None:
        return None
    encoded = artifact_id.removeprefix(S3_DOWNLOAD_FALLBACK_PREFIX)
    try:
        sealed = base64.b64decode(encoded + "=" * (-len(encoded) % 4), altchars=b"-_", validate=True)
        nonce = sealed[:_S3_DOWNLOAD_FALLBACK_NONCE_BYTES]
        ciphertext = sealed[_S3_DOWNLOAD_FALLBACK_NONCE_BYTES:]
        payload = json.loads(_s3_download_fallback_cipher(secret).decrypt(nonce, ciphertext, kid.encode()))
    except (InvalidTag, ValueError):
        return None
    if not isinstance(payload, list) or len(payload) != 3 or not all(isinstance(item, str) for item in payload):
        return None
    download_bucket, key, filename = payload
    if download_bucket != bucket or not key.startswith(f"{DOWNLOAD_FILE_PREFIX}/{environment}/"):
        return None
    parts = key.split("/")
    if (
        len(parts) < 5
        or any(part in {"", ".", ".."} for part in parts)
        or any(ord(char) < 32 for char in key)
        or key.endswith(BROWSER_DOWNLOADING_SUFFIX)
    ):
        return None
    return S3DownloadFallback(key=key, organization_id=parts[2], filename=filename)


def parse_artifact_content_url(url: str, base_url: str) -> ParsedArtifactContentUrl | None:
    """Return the artifact id and signing params when ``url`` addresses ``base_url``'s own
    artifact content endpoint; None for every other URL.

    Scheme, host and any path prefix must match ``base_url`` exactly, so a customer-supplied
    look-alike URL is never mistaken for a first-party one.
    """
    try:
        parts = urlsplit(url)
        base_parts = urlsplit(base_url.rstrip("/"))
    except ValueError:
        return None
    if not base_parts.scheme or not base_parts.netloc:
        return None
    if (parts.scheme, parts.netloc) != (base_parts.scheme, base_parts.netloc):
        return None
    if not parts.path.startswith(base_parts.path):
        return None
    match = _ARTIFACT_CONTENT_PATH_RE.match(parts.path[len(base_parts.path) :])
    if not match:
        return None
    query = dict(parse_qsl(parts.query))
    return ParsedArtifactContentUrl(
        artifact_id=match.group("artifact_id"),
        expiry=query.get("expiry"),
        kid=query.get("kid"),
        sig=query.get("sig"),
    )


def effective_artifact_url_expiry_seconds(per_org_value: int | None) -> int:
    """Return the TTL to mint a signed artifact URL with.

    Falls back to ``ARTIFACT_URL_EXPIRY_SECONDS`` when ``per_org_value`` is
    None. Clamps to ``[ARTIFACT_URL_EXPIRY_SECONDS_MIN, ARTIFACT_URL_EXPIRY_SECONDS_MAX]``
    so an out-of-range stored value still produces a sane URL rather than
    refusing to serve.
    """
    if per_org_value is None:
        return ARTIFACT_URL_EXPIRY_SECONDS
    return max(
        ARTIFACT_URL_EXPIRY_SECONDS_MIN,
        min(ARTIFACT_URL_EXPIRY_SECONDS_MAX, per_org_value),
    )


def artifact_url_expiry_seconds_for_type(
    artifact_type: ArtifactType | None,
    expiry_seconds: int | None,
) -> int | None:
    """Cap a sensitive artifact's URL TTL; pass every other type through unchanged.

    Never lengthens: a caller already asking for a shorter window (the
    on-demand mint endpoint) keeps it.
    """
    if artifact_type not in SENSITIVE_ARTIFACT_TYPES:
        return expiry_seconds
    if expiry_seconds is None:
        return SENSITIVE_ARTIFACT_URL_EXPIRY_SECONDS
    return min(expiry_seconds, SENSITIVE_ARTIFACT_URL_EXPIRY_SECONDS)


class HmacKeyEntry(BaseModel):
    secret: str
    """HMAC secret as a plain string."""
    created_at: str | None = None
    """ISO date string, informational only — not used in signature logic."""


class ArtifactHmacKeyring(BaseModel):
    current_kid: str
    """ID of the key used to sign new URLs."""
    keys: dict[str, HmacKeyEntry]
    """All known keys, including retired ones kept for in-flight URL validation."""

    @model_validator(mode="after")
    def _current_kid_must_be_in_keys(self) -> "ArtifactHmacKeyring":
        if self.current_kid not in self.keys:
            raise ValueError(f"current_kid '{self.current_kid}' is not present in keys")
        return self

    def get_secret_bytes(self, kid: str) -> bytes | None:
        """Return the key bytes for the given kid, or None if the kid is unknown."""
        entry = self.keys.get(kid)
        if entry is None:
            return None
        return entry.secret.encode()


@lru_cache(maxsize=8)
def parse_keyring(keyring_json: str) -> ArtifactHmacKeyring:
    """Parse and validate the ARTIFACT_CONTENT_HMAC_KEYRING JSON string.

    Cached (keyed on the raw JSON) to avoid repeated parsing on every request.
    Different JSON strings (e.g. after a config reload in tests) each get their
    own cached entry.
    """
    data = json.loads(keyring_json)
    return ArtifactHmacKeyring.model_validate(data)


def _canonical_string(method: str, path: str, expiry: int, kid: str) -> str:
    return f"{method}\n{path}\n{expiry}\n{kid}"


def _hmac_b64(secret_bytes: bytes, canonical: str) -> str:
    """Return the URL-safe base64 (no padding) of the HMAC-SHA256 digest."""
    digest = hmac.new(secret_bytes, canonical.encode(), hashlib.sha256).digest()
    return base64.urlsafe_b64encode(digest).rstrip(b"=").decode()


def sign_artifact_url(
    base_url: str,
    artifact_id: str,
    keyring: ArtifactHmacKeyring,
    artifact_name: str | None = None,
    artifact_type: str | None = None,
    expiry_seconds: int | None = None,
) -> str:
    """Return a fully-signed URL for the artifact content endpoint.

    Signs with ``keyring.current_kid``. The URL is valid for ``expiry_seconds``
    from the time this function is called. When ``expiry_seconds`` is None,
    falls back to the global ``ARTIFACT_URL_EXPIRY_SECONDS`` (12 hours).
    Callers wanting a per-org override should resolve it via
    :func:`effective_artifact_url_expiry_seconds` before calling here.

    The signature is URL-safe base64 (no padding), 43 characters for SHA-256.

    ``artifact_name`` and ``artifact_type`` are accepted for call-site
    compatibility but intentionally omitted from the capability URL.
    """
    kid = keyring.current_kid
    secret_bytes = keyring.get_secret_bytes(kid)
    if secret_bytes is None:
        raise ValueError(f"No secret found for kid '{kid}'")

    ttl = expiry_seconds if expiry_seconds is not None else ARTIFACT_URL_EXPIRY_SECONDS
    expiry = int(time.time()) + ttl
    path = _ARTIFACT_CONTENT_PATH_TEMPLATE.format(artifact_id=artifact_id)
    canonical = _canonical_string("GET", path, expiry, kid)
    sig = _hmac_b64(secret_bytes, canonical)
    params = urlencode({"expiry": expiry, "kid": kid, "sig": sig})
    return f"{base_url.rstrip('/')}{path}?{params}"


def verify_artifact_signature(
    artifact_id: str,
    expiry: str,
    kid: str,
    sig: str,
    keyring: ArtifactHmacKeyring,
) -> bool:
    """Return True if the HMAC signature is valid and the URL has not expired.

    Looks up the kid in the keyring so old URLs remain valid while the old key
    is still present, enabling zero-downtime rotation.  All comparisons use
    constant-time equality to prevent timing attacks.
    """
    try:
        expiry_ts = int(expiry)
    except ValueError:
        return False

    if expiry_ts < int(time.time()):
        return False

    secret_bytes = keyring.get_secret_bytes(kid)
    if secret_bytes is None:
        return False

    path = _ARTIFACT_CONTENT_PATH_TEMPLATE.format(artifact_id=artifact_id)
    canonical = _canonical_string("GET", path, expiry_ts, kid)
    expected = _hmac_b64(secret_bytes, canonical)
    return hmac.compare_digest(expected, sig)
